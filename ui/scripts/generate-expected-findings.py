#!/usr/bin/env python3
"""Generate ui/scripts/expected-findings.json from the real Gno Audit().

The five demo realm sources are embedded into a temporary Gno test file
(contracts/demo/vulnmint/auditport_test.gno), which runs the on-chain
auditrules.Audit() against each source and logs every finding. This
script parses that output into expected-findings.json, the ground truth
for scripts/test-audit-port.mjs. The temporary test file is deleted
afterwards, so it never ships.

Run from the project root: python3 ui/scripts/generate-expected-findings.py
Requires the gno toolchain on PATH (see ENV-TOOLCHAIN.md).
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEMO = ROOT / "contracts" / "demo"
REALMS = ["vulnmint", "unguardedvault", "greedystore", "luckydice", "adminbackdoor"]
# The temp test lives in the report realm package, because that package
# is inside the contracts/ workspace that also holds auditrules, so the
# import resolves locally. (The demo workspace only contains the demo
# realms; a test placed there makes gno fetch auditrules from the
# network instead.)
TEST_FILE = ROOT / "contracts" / "realmcheck" / "auditport_test.gno"
OUT_FILE = Path(__file__).resolve().parent / "expected-findings.json"


def main() -> int:
    sources = {}
    for realm in REALMS:
        src_path = DEMO / realm / f"{realm}.gno"
        sources[realm] = src_path.read_text(encoding="utf-8")

    consts = []
    cases = []
    for realm in REALMS:
        # json.dumps produces a double-quoted string whose escapes
        # (\n, \t, \", \\, \uXXXX) are all valid Go string escapes.
        consts.append(f'const {realm}Src = {json.dumps(sources[realm], ensure_ascii=True)}')
        cases.append(f'\t\t{{"{realm}.gno", {realm}Src}},')

    test_src = """package realmcheck

// TEMPORARY, generated by ui/scripts/generate-expected-findings.py.
// Deleted after the run. Do not commit.

import (
\t"strconv"
\t"testing"

\t"gno.land/p/dunoil/auditrules"
)

%s

func TestAuditPortPrint(t *testing.T) {
\tcases := []struct {
\t\tname string
\t\tsrc  string
\t}{
%s
\t}
\tfor _, c := range cases {
\t\tfindings := auditrules.Audit(c.src)
\t\tfor _, f := range findings {
\t\t\tt.Log(c.name + "|" + f.RuleID + "|" + string(f.Severity) + "|" + strconv.Itoa(f.Line) + "|" + f.Title)
\t\t}
\t\tt.Log(c.name + "|COUNT|" + strconv.Itoa(len(findings)))
\t}
}
""" % ("\n".join(consts), "\n".join(cases))

    TEST_FILE.write_text(test_src, encoding="utf-8")
    try:
        proc = subprocess.run(
            ["gno", "test", "-v", "-run", "TestAuditPortPrint", "."],
            cwd=str(ROOT / "contracts" / "realmcheck"),
            capture_output=True,
            text=True,
            timeout=300,
        )
    finally:
        TEST_FILE.unlink(missing_ok=True)

    output = proc.stdout + proc.stderr
    if proc.returncode != 0:
        print("gno test failed (exit %d):" % proc.returncode, file=sys.stderr)
        print(output, file=sys.stderr)
        return 1

    expected = {}
    # gno test -v prefixes each log line with indentation and the
    # test file:line ("    auditport_test.gno:33: ..."), so match
    # mid-line, not at the start. COUNT lines have only three fields.
    finding_re = re.compile(
        r"(vulnmint|unguardedvault|greedystore|luckydice|adminbackdoor)\.gno\|"
        r"(RC-\d\d)\|([^|]*)\|(\d+)\|(.+)$"
    )
    count_re = re.compile(
        r"(vulnmint|unguardedvault|greedystore|luckydice|adminbackdoor)\.gno\|COUNT\|(\d+)"
    )
    for raw in output.splitlines():
        line = raw.strip()
        m = finding_re.search(line)
        if m:
            fname, rule, severity, num, title = m.groups()
            expected.setdefault(f"{fname}.gno", []).append(
                {
                    "ruleID": rule,
                    "severity": severity,
                    "line": int(num),
                    "title": title.strip(),
                }
            )
            continue
        m = count_re.search(line)
        if m:
            expected.setdefault(f"{m.group(1)}.gno", [])

    missing = [f"{r}.gno" for r in REALMS if f"{r}.gno" not in expected]
    if missing:
        print("missing findings for: %s" % ", ".join(missing), file=sys.stderr)
        print(output, file=sys.stderr)
        return 1

    OUT_FILE.write_text(
        json.dumps(expected, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    total = sum(len(v) for v in expected.values())
    print(f"wrote {OUT_FILE} ({total} findings across {len(expected)} realms)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
